# ── Helpers ──
def b(t):  return f'<b>{t}</b>'
def i(t):  return f'<i>{t}</i>'
def mono(t): return f'<font name="{MONO_FONT}">{t}</font>'

def hx(c):
    """ReportLab color -> '#rrggbb'. hexval() returns '0xrrggbb'."""
    return '#' + c.hexval()[2:]

def labeled(label, text, label_color=None):
    """Inline bold label + body, e.g. 'Reveals: ...'"""
    lc = hx(label_color) if label_color else hx(TEXT_PRIMARY)
    return f'<font color="{lc}"><b>{label}</b></font> {text}'

def bullets(items, style=BULLET, marker='•'):
    return [Paragraph(f'{marker}  {x}', style) for x in items]

def question_block(num, title, question, reveals, red_flags, collect=None):
    """Build one Q&A flowable block."""
    block = []
    block.append(Paragraph(f'Q {num}', Q_TAG))
    block.append(Paragraph(b(title), H2))
    block.append(Paragraph(f'<i>“{question}”</i>', QUOTE))
    block.append(Paragraph(labeled('Forensic insight:', reveals), BODY_TIGHT))
    if red_flags:
        block.append(Spacer(1, 2))
        block.append(Paragraph(
            f'<font color="{hx(RED_FLAG)}"><b>Red flags to dig deeper:</b></font>',
            BODY_TIGHT))
        for rf in red_flags:
            block.append(Paragraph(
                f'<font color="{hx(RED_FLAG)}">▸</font>  {rf}',
                RED_STYLE))
    if collect:
        block.append(Spacer(1, 2))
        block.append(Paragraph(
            f'<font color="{hx(COLLECT_GREEN)}"><b>Collect first:</b></font>',
            BODY_TIGHT))
        for c in collect:
            block.append(Paragraph(
                f'<font color="{hx(COLLECT_GREEN)}">⬇</font>  {c}',
                COLLECT_STYLE))
    block.append(Spacer(1, 6))
    return block

def callout_box(title, lines, fill=BG_SURFACE, border=ACCENT):
    """Tinted callout box for triage / summary content."""
    inner = []
    inner.append(Paragraph(f'<b>{title}</b>',
                 ParagraphStyle('CalloutTitle', fontName=HEAD_FONT, fontSize=11.5,
                                leading=14, textColor=border, spaceAfter=4)))
    for ln in lines:
        inner.append(Paragraph(ln,
            ParagraphStyle('CalloutBody', fontName=BODY_FONT, fontSize=10, leading=14,
                           textColor=TEXT_PRIMARY, leftIndent=10, spaceAfter=3)))
    t = Table([[inner]], colWidths=[CONTENT_W])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), fill),
        ('LINEBEFORE', (0,0), (0,-1), 3, border),
        ('LEFTPADDING', (0,0), (-1,-1), 12),
        ('RIGHTPADDING', (0,0), (-1,-1), 12),
        ('TOPPADDING', (0,0), (-1,-1), 10),
        ('BOTTOMPADDING', (0,0), (-1,-1), 10),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
    ]))
    return t

